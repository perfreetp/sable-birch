import { zipSync, strToU8 } from 'fflate';

/** 把字符串按 UTF-8 转成 Blob 并触发下载 */
export function downloadText(filename: string, text: string, mime = 'application/json') {
  downloadBlob(filename, new Blob([text], { type: mime }));
}

export function downloadBlob(filename: string, blob: Blob) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

export function downloadZip(filename: string, files: Record<string, string | Uint8Array>) {
  const entries: Record<string, Uint8Array> = {};
  for (const [name, content] of Object.entries(files)) {
    entries[name] = typeof content === 'string' ? strToU8(content) : content;
  }
  const zipped = zipSync(entries, { level: 6 });
  downloadBlob(filename, new Blob([zipped as unknown as BlobPart], { type: 'application/zip' }));
}

/** 二进制 STL 写出 */
export function buildBinarySTL(positions: Float32Array, index: Uint32Array, header = 'pottery shard merge'): Uint8Array {
  const triCount = index.length / 3;
  const buffer = new ArrayBuffer(84 + triCount * 50);
  const view = new DataView(buffer);
  const bytes = new Uint8Array(buffer);
  const enc = new TextEncoder().encode(header.slice(0, 79));
  bytes.set(enc.subarray(0, 80), 0);
  view.setUint32(80, triCount, true);
  let off = 84;
  const a = [0, 0, 0];
  const b = [0, 0, 0];
  const c = [0, 0, 0];
  for (let t = 0; t < triCount; t++) {
    for (let k = 0; k < 3; k++) {
      a[k] = positions[index[t * 3] * 3 + k];
      b[k] = positions[index[t * 3 + 1] * 3 + k];
      c[k] = positions[index[t * 3 + 2] * 3 + k];
    }
    const ux = b[0] - a[0], uy = b[1] - a[1], uz = b[2] - a[2];
    const vx = c[0] - a[0], vy = c[1] - a[1], vz = c[2] - a[2];
    let nx = uy * vz - uz * vy;
    let ny = uz * vx - ux * vz;
    let nz = ux * vy - uy * vx;
    const len = Math.hypot(nx, ny, nz) || 1;
    nx /= len; ny /= len; nz /= len;
    view.setFloat32(off, nx, true);
    view.setFloat32(off + 4, ny, true);
    view.setFloat32(off + 8, nz, true);
    off += 12;
    for (const p of [a, b, c]) {
      view.setFloat32(off, p[0], true);
      view.setFloat32(off + 4, p[1], true);
      view.setFloat32(off + 8, p[2], true);
      off += 12;
    }
    view.setUint16(off, 0, true);
    off += 2;
  }
  return bytes;
}

/** ASCII OBJ 写出（含顶点与面） */
export function buildOBJ(positions: Float32Array, index: Uint32Array, name = 'merged_shards'): string {
  const lines: string[] = [`# ${name}`, `# generated by 陶俑残片拼合工具`, `o ${name}`];
  const vertCount = positions.length / 3;
  for (let i = 0; i < vertCount; i++) {
    lines.push(`v ${fmt(positions[i * 3])} ${fmt(positions[i * 3 + 1])} ${fmt(positions[i * 3 + 2])}`);
  }
  const triCount = index.length / 3;
  for (let t = 0; t < triCount; t++) {
    lines.push(`f ${index[t * 3] + 1} ${index[t * 3 + 1] + 1} ${index[t * 3 + 2] + 1}`);
  }
  return lines.join('\n');
}

function fmt(v: number) {
  return Number.isInteger(v) ? String(v) : v.toFixed(4);
}
